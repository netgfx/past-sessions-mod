import { describe, expect, test } from 'claude-code/testing'
import {
  fit,
  joinPath,
  lastActive,
  longDate,
  matchesQuery,
  queryTerms,
  orderSessions,
  projectDirName,
  promptOf,
  sessionIdOf,
  shortAge,
  summarize,
  visibleSessions,
} from '../hooks/lib.js'

const ID = '3a07c375-ab56-4dfa-a20a-cd4ed30064a0'

describe('names and paths', () => {
  test('session ids come only from uuid .jsonl names', async () => {
    expect(sessionIdOf(ID + '.jsonl')).toBe(ID)
    expect(sessionIdOf('memory')).toBe(null)
    expect(sessionIdOf(ID + '.json')).toBe(null)
  })

  test('project folder names match Claude Code on both platforms', async () => {
    expect(projectDirName('D:\\Projects\\claude-plugins\\past-sessions-mod')).toBe('D--Projects-claude-plugins-past-sessions-mod')
    expect(projectDirName('/Users/me/my_app')).toBe('-Users-me-my-app')
  })

  test('joinPath keeps the native separator', async () => {
    expect(joinPath('C:\\Users\\me\\.claude', 'projects')).toBe('C:\\Users\\me\\.claude\\projects')
    expect(joinPath('/Users/me/.claude/', 'projects')).toBe('/Users/me/.claude/projects')
  })
})

const row = (o: object) => JSON.stringify(o)
const user = (content: unknown, extra: object = {}) =>
  row({ type: 'user', message: { role: 'user', content }, timestamp: '2026-10-04T08:33:24.863Z', gitBranch: 'main', ...extra })

describe('summarize', () => {
  test('reads the title, first and last prompt, and skips engine rows', async () => {
    const text = [
      row({ type: 'mode', mode: 'normal' }),
      user('Caveat: The messages below were generated by the user while running local commands.', { isMeta: true }),
      user('<command-name>/clear</command-name><command-args></command-args>'),
      user('fix the login bug\nit fails on Windows'),
      user([{ type: 'tool_result', tool_use_id: 't', content: 'ok' }]),
      row({ type: 'ai-title', aiTitle: 'Old title' }),
      row({ type: 'assistant', message: { content: [] }, timestamp: '2026-10-05T10:00:00.000Z' }),
      user([{ type: 'text', text: 'now add a test' }]),
      row({ type: 'ai-title', aiTitle: 'Login bug fix on Windows' }),
      '{"type":"user","message":{"cont', // a line cut mid-write
    ].join('\r\n')
    const s = summarize(text)
    expect(s.title).toBe('Login bug fix on Windows')
    expect(s.firstPrompt).toBe('/clear')
    expect(s.lastPrompt).toBe('now add a test')
    expect(s.prompts).toBe(3)
    expect(s.branch).toBe('main')
    expect(s.startedAt).toBe(Date.parse('2026-10-04T08:33:24.863Z'))
  })

  test('a /rename title wins, and the first prompt is the fallback', async () => {
    expect(summarize([user('hello'), row({ type: 'custom-title', customTitle: 'Mine' })].join('\n')).title).toBe('Mine')
    expect(summarize(user('build a pane\nwith tabs')).title).toBe('build a pane')
  })

  test('a transcript with no prompt, or only bare commands, counts as empty', async () => {
    expect(summarize(row({ type: 'mode', mode: 'normal' })).substantive).toBe(0)
    expect(summarize(user('<command-name>/reload-plugins</command-name>')).substantive).toBe(0)
    expect(summarize(user('<command-name>/graphify</command-name><command-args>./src</command-args>')).substantive).toBe(1)
  })

  test('system reminders are stripped from prompts', async () => {
    expect(promptOf(JSON.parse(user('<system-reminder>x</system-reminder>do it')))).toBe('do it')
  })
})

describe('ordering', () => {
  const s = (id: string, mtimeMs: number, isEmpty = false) => ({ id, mtimeMs, size: 1, summary: { isEmpty } })
  const all = [s('a', 1), s('b', 2), s('c', 3), s('d', 4), s('e', 5), s('f', 6), s('g', 7), s('h', 8), s('empty', 9, true)]

  test('pinned first, then newest first, the pinned newest first too', async () => {
    const order = orderSessions(all, new Set(['a', 'c'])).map((x) => x.id)
    expect(order.slice(0, 3)).toEqual(['c', 'a', 'empty'])
  })

  test('collapsed shows every pinned one plus the newest five others', async () => {
    const v = visibleSessions(all, { pins: new Set(['a', 'b']), archived: new Set(['h']), expanded: false })
    expect(v.pinned.map((x) => x.id)).toEqual(['b', 'a'])
    expect(v.others.map((x) => x.id)).toEqual(['g', 'f', 'e', 'd', 'c'])
    expect(v.hidden).toBe(0)
  })

  test('More counts what expanding would add', async () => {
    const v = visibleSessions(all, { pins: new Set(), archived: new Set(), expanded: false })
    expect(v.others.length).toBe(5)
    expect(v.hidden).toBe(3)
    expect(visibleSessions(all, { pins: new Set(), archived: new Set(), expanded: true }).others.length).toBe(8)
  })
})

test('ages and fitting', async () => {
  const now = Date.parse('2026-10-21T12:00:00Z')
  expect(shortAge(now - 30_000, now)).toBe('now')
  expect(shortAge(now - 5 * 60_000, now)).toBe('5m')
  expect(shortAge(now - 3 * 3600_000, now)).toBe('3h')
  expect(shortAge(Date.parse('2025-03-01T12:00:00Z'), now)).toBe('Mar 1 2025')
  expect(fit('abcdef', 4)).toBe('abc…')
  expect(lastActive(now - 30_000, now)).toBe('active now')
  expect(lastActive(now - 3 * 3600_000, now)).toBe('last active 3h ago')
  expect(lastActive(Date.parse('2025-03-01T12:00:00Z'), now)).toBe('last active Mar 1 2025')
  expect(longDate(Date.parse('2026-03-01T12:00:00Z'), now)).toMatch(/^Mar 1, \d\d:\d\d$/)
  expect(longDate(Date.parse('2025-03-01T12:00:00Z'), now)).toMatch(/^Mar 1 2025, \d\d:\d\d$/)
})

test('search terms all have to match, in any field', async () => {
  const s = { id: 'abc-123', summary: { title: 'Dark mode', firstPrompt: 'add a toggle', lastPrompt: 'ship it', branch: 'feat/theme' } }
  expect(queryTerms('  Dark   TOGGLE ')).toEqual(['dark', 'toggle'])
  expect(matchesQuery(s, queryTerms('dark toggle'))).toBe(true)
  expect(matchesQuery(s, queryTerms('theme'))).toBe(true)
  expect(matchesQuery(s, queryTerms('abc'))).toBe(true)
  // an id matches from its start only
  expect(matchesQuery(s, queryTerms('123'))).toBe(false)
  expect(matchesQuery(s, queryTerms('dark light'))).toBe(false)
  expect(matchesQuery({ id: 'x', summary: null }, queryTerms('x'))).toBe(false)
  expect(matchesQuery({ id: 'x', summary: null }, [])).toBe(true)
})
